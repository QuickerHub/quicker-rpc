import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const apiRoot = join(root, "app", "api");
async function scan(directory) {
  const files = await Promise.all((await readdir(directory, { withFileTypes: true })).map(async (entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? scan(path) : entry.name === "route.ts" ? [path] : [];
  }));
  return files.flat();
}
const rows = [];
for (const file of (await scan(apiRoot)).sort()) {
  const path = `/api/${relative(apiRoot, dirname(file)).replaceAll("\\", "/")}`;
  if (path === "/api/chat") continue; // Chat uses the injected, single application runner.
  const source = await readFile(file, "utf8");
  const methods = [...source.matchAll(/export (?:async function|const) (GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\b/g)].map((m) => m[1]);
  rows.push(`  { path: ${JSON.stringify(path)}, methods: ${JSON.stringify(methods)}, load: () => import(${JSON.stringify(`../../app/api/${relative(apiRoot, file).replaceAll("\\", "/").replace(/\.ts$/, "")}`)}) },`);
}
const output = `// Generated by scripts/generate-service-routes.mjs; handlers remain the single API source.\nexport const agentApiRoutes = [\n${rows.join("\n")}\n] as const;\n`;
const target = join(root, "lib", "agent-service", "api-routes.generated.ts");
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== output) throw new Error("Agent API route manifest is stale");
} else await writeFile(target, output);
console.log(`Agent API manifest: ${rows.length} routes`);
